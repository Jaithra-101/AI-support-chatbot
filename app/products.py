"""Product questions, answered only from the catalog (data/products.json).

    "How much are the earbuds?"            exact fact     -> straight from the database
    "Does the smartwatch come in blue?"    exact fact     -> checks the colour list
    "Can I swim with it?"                  spec question  -> "it" = last product discussed
    "Earbuds vs headphones battery?"       comparison     -> the spec for each product
    "Can I reply to messages on the watch?" product Q&A   -> closest stored Q&A
    "Is the bottle good for hiking?"       open question  -> QA model reads that product's page only
    "Show me audio under 3000"             search         -> price filter + semantic ranking
    "Does the speaker support Alexa?"      unknown        -> honest "not in our specs" + ticket

Prices, stock and specs are never generated by a model, so the bot can't
invent a wrong price or a feature the product doesn't have.
"""
import json
import re

import numpy as np

from . import store
from .config import DATA_DIR
from .nlp import split_sentences

CATALOG_PATH = DATA_DIR / "products.json"

# Words that point at a fact. Several can match; we answer the ones the product has.
ATTRIBUTES = {
    "price": r"price|cost|how much|mrp|expensive|cheap|rate of",
    "stock": r"in stock|stock|available|availability|sold out|out of stock|any left",
    "colours": r"colou?rs?|shades?",
    "sizes": r"sizes?|uk \d+",
    "warranty": r"warranty|guarantee",
    "battery": r"battery|backup|how long (does|will) (it|the battery) last|mah",
    "charging": r"charging|charge it|wireless charg|fast charg|how long to charge",
    "noise cancellation": r"noise|anc",
    "water resistance": r"water|waterproof|swim|shower|rain|sweat|ip ?x?\d",
    "gps": r"gps|navigation",
    "display": r"display|screen",
    "connectivity": r"bluetooth|connect|pair|android|iphone|ios|windows|mac ?os|work with",
    "compatibility": r"compatib|which phones|fit (my|an?) (iphone|samsung|phone)|iphone|samsung",
    "sensors": r"heart rate|spo2|oxygen|sleep|sensors?|steps",
    "capacity": r"capacity|litres?|liters?|\bml\b|how much (does it|can it) hold|fit (a|my) laptop|inch laptop|mah",
    "material": r"material|made of|fabric|cotton|plastic|leather|latex",
    "weight": r"weight|heavy|weigh|lightweight",
    "dimensions": r"dimensions?|how (big|wide|long|tall|thick)|length|width|height|thickness",
    "power": r"watts?|wattage|power|output",
    "care": r"wash|clean|dishwasher|microwave",
    "fit": r"\bfit\b|true to size|size up|size down",
    "insulation": r"hot|cold|insulat",
    "protection": r"protect|drop|uv",
    "in the box": r"in the box|comes with|included|box contents",
    "features": r"features?|timer|presets?",
    "ports": r"ports?|usb",
    "resolution": r"resolution|1080p|4k|quality",
}
_ATTR_RE = {k: re.compile(rf"\b(?:{v})", re.I) for k, v in ATTRIBUTES.items()}

# Questions about store policy, not the product itself -> leave them to the help-centre documents
POLICY_WORDS = re.compile(r"\b(return|refund|deliver|delivery|shipping|ship|exchange|cancel(?! noise)|emi|"
                          r"cash on delivery|cod|invoice|coupon|discount|payment|pay|"
                          r"broke|broken|damaged?|cracked|dropped|spilled|defective|faulty)\b", re.I)
PRONOUN = re.compile(r"\b(it|its|this|that|these|those|they|them|one)\b|^\s*(and|what about|how about)\b", re.I)
OVERVIEW = re.compile(r"\b(tell me about|details|info|information|describe|specs|specifications|features|"
                      r"what is the|what's the|buy|want|interested|show me the)\b", re.I)
PRODUCT_QUESTION = re.compile(r"^\s*(does|do|can|is|are|will|has|have|how|what|which)\b", re.I)
SEARCH = re.compile(r"\b(show me|do you (have|sell|stock|carry)|looking for|recommend|suggest|cheapest|"
                    r"best \w+|gift for|options|what \w+ do you (have|sell)|any \w+ (under|below)|"
                    r"(something|anything|ideas?) for|need (a|an|some)|under|below|less than|within|budget)\b", re.I)
CATEGORY_WORDS = {
    "Audio": r"audio|music|sound|headphones?|earphones?|speakers?",
    "Wearables": r"wearables?|watch(es)?|fitness trackers?",
    "Bags": r"bags?|backpacks?",
    "Footwear": r"footwear|shoes|sneakers",
    "Clothing": r"cloth(es|ing)|apparel|wear\b|shirts?",
    "Fitness": r"fitness|gym|workout|exercise|yoga",
    "Home & Kitchen": r"home|kitchen|cooking|appliances?",
    "Computer Accessories": r"computer|pc\b|desk setup|work from home",
    "Accessories": r"phone accessories|mobile accessories",
}
_CATEGORY_RE = {k: re.compile(rf"\b(?:{v})", re.I) for k, v in CATEGORY_WORDS.items()}
MAX_PRICE = re.compile(r"\b(?:under|below|less than|within|up ?to|budget(?: of)?)\s*(?:rs\.?|₹|inr)?\s*(\d[\d,]*)", re.I)
MIN_PRICE = re.compile(r"\b(?:above|over|more than)\s*(?:rs\.?|₹|inr)?\s*(\d[\d,]*)", re.I)


def _rupees(n: int) -> str:
    return f"₹{n:,}"


class ProductCatalog:
    def __init__(self, embed, qa):
        self.embed = embed  # sentence-embedding function (shared with the document store)
        self.qa = qa        # extractive QA function (shared with the document store)
        self.products = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
        names = []
        for i, p in enumerate(self.products):
            p["id"] = i + 1
            names += [(n.lower(), i) for n in [p["name"], *p.get("aliases", [])]]
        # longest names first so "wireless earbuds" beats "earbuds"
        names.sort(key=lambda x: -len(x[0]))
        self._names = [(re.compile(rf"\b{re.escape(n)}s?\b", re.I), i) for n, i in names]
        self.colours = {c.lower() for p in self.products for c in p["colours"]}
        self._vectors = None
        self._qa_vectors = None

    # ---- lookups ----------------------------------------------------------------

    def vocabulary(self) -> list[str]:
        """Product words for the spell corrector."""
        return [w for p in self.products for w in [p["name"], *p.get("aliases", []), p["category"]]]

    def find(self, text: str) -> list[dict]:
        """Products mentioned in the text, in order of mention."""
        found, taken = [], []
        for pattern, i in self._names:
            for m in pattern.finditer(text):
                if any(a < m.end() and m.start() < b for a, b in taken):
                    continue  # part of a longer name already matched
                taken.append((m.start(), m.end()))
                found.append((m.start(), i))
        seen = []
        for _, i in sorted(found):
            if i not in seen:
                seen.append(i)
        return [self.products[i] for i in seen]

    def _strip_names(self, text: str) -> str:
        for pattern, _ in self._names:
            text = pattern.sub(" ", text)
        return re.sub(r"\s+", " ", text).strip()

    def attributes(self, text: str) -> list[str]:
        text = self._strip_names(text)  # "bluetooth speaker" is not a question about bluetooth
        found = [k for k, pattern in _ATTR_RE.items() if pattern.search(text)]
        if "colours" not in found and any(re.search(rf"\b{re.escape(c)}\b", text, re.I) for c in self.colours):
            found.append("colours")  # "do they come in white?"
        return found

    def card(self, p: dict) -> dict:
        stock = store.product_stock(p["id"])
        return {"id": p["id"], "name": p["name"], "category": p["category"], "price": p["price"],
                "stock": stock, "colours": p["colours"], "description": p["description"]}

    # ---- answering ----------------------------------------------------------------

    def _fact(self, p: dict, attr: str, text: str) -> str | None:
        name = p["name"]
        plural = name.endswith("s") and not name.endswith("ss")  # "Running Shoes are", "Smartwatch is"
        be, has, does = ("are", "have", "don't") if plural else ("is", "has", "doesn't")
        comes, costs = ("come", "cost") if plural else ("comes", "costs")
        if attr == "price":
            return f"The {name} {costs} {_rupees(p['price'])} (including GST)."
        if attr == "stock":
            n = store.product_stock(p["id"])
            if n == 0:
                return f"The {name} {be} out of stock right now. Tap Notify Me on the product page to get an email when it's back."
            return f"Yes, the {name} {be} in stock" + (f" (only {n} left)." if n < 10 else ".")
        if attr == "colours":
            asked = [c for c in self.colours if re.search(rf"\b{re.escape(c)}\b", text, re.I)]
            options = ", ".join(p["colours"])
            if asked:
                have = [c for c in asked if c in {x.lower() for x in p["colours"]}]
                if have:
                    return f"Yes, the {name} {comes} in {have[0].title()}. All colours: {options}."
                return f"Sorry, the {name} {does} come in {asked[0].title()}. Available colours: {options}."
            return f"The {name} {comes} in {options}."
        if attr == "sizes":
            if not p["sizes"]:
                return f"The {name} {comes} in one size."
            asked = next((s for s in p["sizes"] if re.search(rf"\b{re.escape(s)}\b", text, re.I)), None)
            if asked:
                return f"Yes, the {name} {be} available in {asked}. Sizes: {', '.join(p['sizes'])}."
            return f"The {name} {be} available in sizes {', '.join(p['sizes'])}."
        if attr == "warranty":
            months = p.get("warranty_months", 0)
            return (f"The {name} {has} a {months}-month warranty against manufacturing defects."
                    if months else f"The {name} {does} come with a warranty, but our 30-day return policy applies.")
        value = p["specs"].get(attr)
        return f"{name}, {attr}: {value}." if value else None

    def _product_text(self, p: dict) -> str:
        specs = " ".join(f"{k.capitalize()}: {v}." for k, v in p["specs"].items())
        qa = " ".join(f"{q} {a}" for q, a in p["qa"])
        return f"{p['description']} {specs} {qa}"

    def _best_qa(self, p: dict, question: str) -> tuple[str, float] | None:
        if not p["qa"]:
            return None
        questions = [q for q, _ in p["qa"]]
        scores = self.embed(questions) @ self.embed([question])[0]
        i = int(scores.argmax())
        return p["qa"][i][1], float(scores[i])

    def answer(self, text: str, products: list[dict]) -> dict | None:
        """Answer a question about specific products. None = not a product question."""
        if POLICY_WORDS.search(text):
            return None  # "can I return the earbuds?", "exchange shoes for another size" -> help centre
        attrs = self.attributes(text)
        question = self._strip_names(text) or text  # "can i take the power bank on a plane" -> "can i take the on a plane"

        if len(products) == 1:
            best = self._best_qa(products[0], question)
            if best and best[1] >= 0.6:
                return {"reply": best[0], "products": [self.card(products[0])], "confidence": round(best[1], 3)}

        lines, missing = [], []
        for p in products:
            for attr in attrs:
                fact = self._fact(p, attr, text)
                if fact:
                    lines.append(fact)
                elif attr not in ("colours", "sizes"):
                    missing.append((p, attr))
            if attrs and not any(p["name"] in line for line in lines):
                missing.append((p, attrs[0]))
        if lines:
            return {"reply": "\n".join(dict.fromkeys(lines)), "products": [self.card(p) for p in products],
                    "confidence": 1.0}

        if len(products) == 1 and not missing:  # a known spec that's missing must not be guessed from the description
            p = products[0]
            if OVERVIEW.search(text) or len(question.split()) <= 1:
                return {"reply": self.overview(p), "products": [self.card(p)], "confidence": 1.0}
            context = self._product_text(p)
            result = self.qa(question=text, context=context)
            span = result["answer"].strip()
            if result["score"] >= 0.5 and span:
                sentence = next((s for s in split_sentences(context) if span in s), span)
                return {"reply": f"{sentence} (From the {p['name']} product page.)", "highlight": span,
                        "products": [self.card(p)], "confidence": round(result["score"], 3)}
            # reader unsure: quote the closest sentence of the product page if it's clearly related
            sentences = split_sentences(context)
            scores = self.embed(sentences) @ self.embed([question])[0]
            if scores.max() >= 0.45:
                return {"reply": f"{sentences[int(scores.argmax())]} (From the {p['name']} product page.)",
                        "products": [self.card(p)], "confidence": round(float(scores.max()), 3)}

        if missing or PRODUCT_QUESTION.search(text):
            p = (missing[0][0] if missing else products[0])
            return {"unknown": True, "products": [self.card(p)], "confidence": 0.0,
                    "reply": f"I don't have that detail for the {p['name']} in our product information, and "
                             f"I'd rather not guess. Leave your email and our product team will confirm."}
        return None

    def overview(self, p: dict) -> str:
        top = list(p["specs"].items())[:3]
        specs = "\n".join(f"• {k.capitalize()}: {v}" for k, v in top)
        return f"{p['name']}: {_rupees(p['price'])}\n{p['description']}\n{specs}"

    # ---- search ----------------------------------------------------------------

    def is_search(self, text: str) -> bool:
        return bool(SEARCH.search(text))

    def search(self, text: str, limit: int = 3) -> dict:
        if self._vectors is None:
            self._vectors = self.embed([f"{p['name']}. {p['category']}. {' '.join(p.get('aliases', []))}. "
                                        f"{p['description']}" for p in self.products])
        cap = MAX_PRICE.search(text)
        floor = MIN_PRICE.search(text)
        cap = int(cap.group(1).replace(",", "")) if cap else None
        floor = int(floor.group(1).replace(",", "")) if floor else None
        categories = {c for c, pattern in _CATEGORY_RE.items() if pattern.search(text)}
        query = MIN_PRICE.sub("", MAX_PRICE.sub("", text))
        scores = self._vectors @ self.embed([query])[0]
        ranked = [(float(scores[i]), p) for i, p in enumerate(self.products)
                  if (cap is None or p["price"] <= cap) and (floor is None or p["price"] >= floor)
                  and (not categories or p["category"] in categories)]
        ranked.sort(key=lambda x: -x[0])
        price_note = (f" under {_rupees(cap)}" if cap else "") + (f" above {_rupees(floor)}" if floor else "")
        if not ranked:
            what = " or ".join(sorted(categories)).lower() + " products" if categories else "products"
            return {"reply": f"Sorry, we don't have any {what}{price_note}.", "products": [], "confidence": 0.0}
        top = [p for s, p in ranked[:limit] if s >= 0.2] or [ranked[0][1]]
        best = ranked[0][0]
        weak = best < 0.3 and not categories and cap is None and floor is None
        if categories or best >= 0.3:
            head = f"Here's what I found{price_note}:"
        else:
            head = f"I couldn't find an exact match{price_note}. These are the closest items we sell:"
        return {"reply": head, "products": [self.card(p) for p in top], "confidence": round(best, 3), "weak": weak}
